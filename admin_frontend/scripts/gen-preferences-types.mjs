#!/usr/bin/env node
/**
 * Regenerate preferences types + defaults from the backend Pydantic model.
 *
 * Outputs (committed):
 * - schemas/workspace-preferences.schema.json
 * - src/lib/api/generated/workspace-preferences.defaults.json
 * - src/lib/api/generated/preferences.generated.ts
 * - src/lib/api/generated/workspace-preferences.defaults.ts
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileFromFile } from 'json-schema-to-typescript';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const adminRoot = path.resolve(__dirname, '..');
const repoRoot = path.resolve(adminRoot, '..');
const hirocliRoot = path.join(repoRoot, 'hiroserver', 'hirocli');

const schemaJsonPath = path.join(adminRoot, 'schemas', 'workspace-preferences.schema.json');
const generatedDir = path.join(adminRoot, 'src', 'lib', 'api', 'generated');
const defaultsJsonPath = path.join(generatedDir, 'workspace-preferences.defaults.json');
const fieldSchemaJsonPath = path.join(generatedDir, 'preferences-field-schema.json');
const generatedTypesPath = path.join(generatedDir, 'preferences.generated.ts');
const defaultsTsPath = path.join(generatedDir, 'workspace-preferences.defaults.ts');

mkdirSync(path.dirname(schemaJsonPath), { recursive: true });
mkdirSync(generatedDir, { recursive: true });

execFileSync(
  'uv',
  [
    'run',
    'python',
    path.join(hirocliRoot, 'scripts', 'emit_workspace_preferences_codegen.py'),
    '--schema-out',
    schemaJsonPath,
    '--defaults-out',
    defaultsJsonPath,
    '--field-schema-out',
    fieldSchemaJsonPath
  ],
  { cwd: hirocliRoot, stdio: 'inherit' }
);

const generatedTypes = await compileFromFile(schemaJsonPath, {
  bannerComment:
    '/* eslint-disable */\n/** AUTO-GENERATED by `npm run gen:prefs-types` — do not edit. */',
  additionalProperties: false,
  enableConstEnums: true,
  declareExternallyReferenced: true
});

writeFileSync(generatedTypesPath, `${generatedTypes.trim()}\n`, 'utf8');

const defaultsJson = readFileSync(defaultsJsonPath, 'utf8');
const defaultsTs = `/* eslint-disable */
/** AUTO-GENERATED by \`npm run gen:prefs-types\` — do not edit. */
import type { WorkspacePreferences } from './preferences.generated';

export const DEFAULT_WORKSPACE_PREFERENCES = ${defaultsJson.trim()} as WorkspacePreferences;
`;

writeFileSync(defaultsTsPath, defaultsTs, 'utf8');

console.log('Generated preferences types and defaults.');
