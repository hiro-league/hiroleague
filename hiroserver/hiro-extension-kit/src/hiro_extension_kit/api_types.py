"""The frontend's API types from the backend's API description (OpenAPI): what each app's scripts/api_types.py
writes to frontend/src/lib/api/generated.ts (`cd backend && uv run python scripts/api_types.py`). One TypeScript
type per model the routes declare (inputs and answers). Never edit that file by hand; each app's
tests/test_api_types.py fails when it is out of date. Backend kit, step 6: each app had a copy of this code.

A field is optional (`?`) when the schema doesn't require it: inputs with a default, and answers'
fields with a default, which routes that answer only the keys that were set leave out. Answer models
that always send every field say so (json_schema_serialization_defaults_required). Models that pass unknown keys on (extra="allow")
get no index signature: TypeScript's Omit would turn every named field of such a type into unknown.
"""

import json
import re

HEADER = """// Generated by backend/scripts/api_types.py from the backend's API description. Do not edit:
// change the backend's models and run `cd backend && uv run python scripts/api_types.py`.
"""
IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
MODULE_QUALIFIED = re.compile(r"^[a-z][a-z0-9_]*?__")  # "nethiro__auth__api__UserIn"


def type_name(name: str) -> str:
    """FastAPI's schema names ("PlanDoc-Input", "Body_upload_image") as TypeScript names."""
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^A-Za-z0-9]+", name) if part)


def ts(schema: dict, indent: str = "") -> str:
    if "$ref" in schema:
        return type_name(schema["$ref"].rsplit("/", 1)[1])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            parts = list(dict.fromkeys(ts(s, indent) for s in schema[key]))
            return " | ".join(parts)
    if "allOf" in schema:
        return " & ".join(ts(s, indent) for s in schema["allOf"])
    kind = schema.get("type")
    if kind == "null":
        return "null"
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        if "prefixItems" in schema:
            return "[" + ", ".join(ts(s, indent) for s in schema["prefixItems"]) + "]"
        item = ts(schema.get("items") or {}, indent)
        return f"({item})[]" if " " in item else f"{item}[]"
    if kind == "object" or "properties" in schema:
        props = schema.get("properties") or {}
        extra = schema.get("additionalProperties")
        if not props:
            if extra in (None, True, {}):
                return "Record<string, unknown>"
            return f"Record<string, {ts(extra, indent)}>"
        required = set(schema.get("required") or [])
        inner = indent + "\t"
        lines = []
        for name, prop in props.items():
            optional = name not in required
            key = name if IDENT.match(name) else json.dumps(name)
            lines.append(f"{inner}{key}{'?' if optional else ''}: {ts(prop, inner)};")
        return "{\n" + "\n".join(lines) + f"\n{indent}}}"
    return "unknown"


def clashes(spec: dict) -> list[str]:
    """Models that share a name: FastAPI then names each after its module ("nethiro__auth__api__UserIn", or the kit's
    "hiro_extension_kit__auth__api__UserIn"), and the frontend's short name silently disappears. Every model needs a name
    of its own. (A module's name starts with a lower-case letter; FastAPI's own Body_<route> names don't.)"""
    return sorted(n for n in spec.get("components", {}).get("schemas", {}) if MODULE_QUALIFIED.match(n))


def generate(spec: dict) -> str:
    if found := clashes(spec):
        raise SystemExit("Two models share a name; rename one of each (the frontend's types would lose them):\n  "
                         + "\n  ".join(found))
    out = [HEADER]
    for name, schema in sorted(spec.get("components", {}).get("schemas", {}).items()):
        doc = schema.get("description")
        if doc:
            out.append("/** " + " ".join(doc.split()) + " */")
        out.append(f"export type {type_name(name)} = {ts(schema)};\n")
    return "\n".join(out)
